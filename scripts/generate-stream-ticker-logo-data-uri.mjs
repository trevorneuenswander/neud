#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const logoPath = path.join(repoRoot, "public", "displays", "pylon", "logo.png");
const outputDir = path.join(repoRoot, "shared", "display-runtime");
const outputTsPath = path.join(outputDir, "stream-ticker-logo-data-uri.generated.ts");
const outputJsPath = path.join(outputDir, "stream-ticker-logo-data-uri.generated.js");

if (!fs.existsSync(logoPath)) {
  console.error(`Missing logo asset: ${logoPath}`);
  process.exit(1);
}

const base64 = fs.readFileSync(logoPath).toString("base64");
const dataUri = `data:image/png;base64,${base64}`;
const tsContents = `/** Generated by scripts/generate-stream-ticker-logo-data-uri.mjs — do not edit. */
export const STREAM_TICKER_LOGO_DATA_URI =
  "${dataUri}";
`;
const jsContents = `/** Generated by scripts/generate-stream-ticker-logo-data-uri.mjs — do not edit. */
export const STREAM_TICKER_LOGO_DATA_URI =
  "${dataUri}";
`;

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(outputTsPath, tsContents, "utf8");
fs.writeFileSync(outputJsPath, jsContents, "utf8");
console.log(`Wrote ${outputTsPath}`);
console.log(`Wrote ${outputJsPath}`);
