export function matchStoredDevice(
  deviceId: string,
  devices: OutputDevice[],
  rememberedElectronId: number | null,
  rememberedLabel: string,
  rememberedWidth: number | null,
  rememberedHeight: number | null,
): OutputDevice | null {
  const displays = devices.filter(
    (device): device is OutputDevice & { capabilities: ComputerDisplayCapabilities } =>
      device.capabilities.kind === "computer-display",
  );
  const exact = displays.find((device) => device.id === deviceId);
  if (exact) return exact;
  if (rememberedElectronId != null) {
    const byPort = displays.filter(
      (device) => device.capabilities.electronDisplayId === rememberedElectronId,
    );
    if (byPort.length === 1) return byPort[0] ?? null;
  }
  const label = normalizeDisplayLabel(rememberedLabel);
  const byLabel = displays.filter((device) => {
    const sameLabel = normalizeDisplayLabel(device.name) === label;
    const sameSize =
      rememberedWidth == null ||
      rememberedHeight == null ||
      (device.capabilities.width === rememberedWidth &&
        device.capabilities.height === rememberedHeight);
    return sameLabel && sameSize;
  });
  return byLabel.length === 1 ? (byLabel[0] ?? null) : null;
}

export function matchDeckLinkDevice(route: OutputRoute, devices: OutputDevice[]): OutputDevice | null {
  const endpoints = devices.filter((device) => device.capabilities.kind === "decklink");
  const exact = endpoints.find((device) => device.id === route.deviceId);
  if (exact) return exact;
  const saved = route.configuration.decklink;
  if (!saved) return null;
  return (
    endpoints.find((device) => {
      if (device.capabilities.kind !== "decklink") return false;
      return (
        device.capabilities.persistentId === saved.persistentId &&
        device.capabilities.endpointIndex === saved.endpointIndex
      );
    }) ?? null
  );
}

