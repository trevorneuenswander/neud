export function buildOutputRenderUrl(input: {
  origin: string;
  projectId: string;
  slug: string;
  authoredWidth: number;
  authoredHeight: number;
  outputWidth: number;
  outputHeight: number;
  hideCursor?: boolean;
}): string {
  const origin = input.origin.replace(/\/$/, "");
  // Load the published HTML document directly inside window-fit.
  // Do NOT nest /display/... (another full Next.js page) — that doubled React
  // hydration + layout at authored UHD and starved the operator UI (Pass 9).
  const docParams = new URLSearchParams({ output: "1" });
  if (input.hideCursor !== false) {
    docParams.set("surface", "computer");
    docParams.set("hideCursor", "1");
  }
  const outputPath = `${origin}/api/display-html/${encodeURIComponent(input.projectId)}/${encodeURIComponent(input.slug)}?${docParams.toString()}`;
  const params = new URLSearchParams({
    target: outputPath,
    width: String(input.authoredWidth),
    height: String(input.authoredHeight),
    surface: "computer",
    cursor: input.hideCursor === false ? "auto" : "none",
  });
  return `${origin}/display/window-fit?${params.toString()}`;
}

/**
 * Stack compositor URL: one viewport-fit surface with absolute published-display
 * iframe layers. Does not screenshot the pinned UI.
 */
export function buildOutputStackRenderUrl(input: {
  origin: string;
  projectId: string;
  stackId: string;
  layers: Array<{
    displayId: string;
    slug: string;
    zIndex: number;
    width?: number;
    height?: number;
  }>;
  authoredWidth: number;
  authoredHeight: number;
  surface: "computer" | "decklink";
  hideCursor?: boolean;
  outputWidth?: number;
  outputHeight?: number;
}): string {
  const origin = input.origin.replace(/\/$/, "");
  const params = new URLSearchParams({
    projectId: input.projectId,
    stackId: input.stackId,
    width: String(input.authoredWidth),
    height: String(input.authoredHeight),
    surface: input.surface,
    layers: JSON.stringify(
      input.layers.map((layer) => ({
        displayId: layer.displayId,
        slug: layer.slug,
        zIndex: layer.zIndex,
        ...(typeof layer.width === "number" && layer.width > 0 ? { width: layer.width } : {}),
        ...(typeof layer.height === "number" && layer.height > 0 ? { height: layer.height } : {}),
      })),
    ),
  });
  if (input.surface === "computer") {
    params.set("cursor", input.hideCursor === false ? "auto" : "none");
  }
  if (input.outputWidth && input.outputHeight) {
    params.set("outputWidth", String(input.outputWidth));
    params.set("outputHeight", String(input.outputHeight));
  }
  return `${origin}/display/stack-fit?${params.toString()}`;
}

/** Normalize legacy routes that only stored `displayId` into sourceType/sourceId. */
export function normalizeOutputRouteSource(input: {
  displayId?: string | null;
  sourceType?: string | null;
  sourceId?: string | null;
}): { sourceType: OutputSourceType; sourceId: string; displayId: string } {
  const rawType = input.sourceType === "stack" ? "stack" : "display";
  const legacyDisplayId = typeof input.displayId === "string" ? input.displayId.trim() : "";
  const rawSourceId = typeof input.sourceId === "string" ? input.sourceId.trim() : "";

  if (rawType === "stack") {
    return {
      sourceType: "stack",
      sourceId: rawSourceId || legacyDisplayId,
      // Never overload displayId with a stack id.
      displayId: "",
    };
  }

  const sourceId = rawSourceId || legacyDisplayId;
  return {
    sourceType: "display",
    sourceId,
    displayId: sourceId,
  };
}

