export class OutputEngine {
  private readonly sessions = new Map<string, OutputSession>();
  private memoryOutputSequence = 1;
  private readonly deps: {
    store: OutputRouteStore;
    windows: OutputWindowHost;
    discoverDevices: () => OutputDevice[];
    resolveDisplay: (displayId: string) => ResolvedOutputDisplay | null;
    resolveStack?: (stackId: string, projectId: string) => ResolvedOutputStack | null;
    origin: () => string;
    now?: () => string;
    decklink?: DeckLinkEnginePort;
    diskRecording?: DiskRecordingService;
    resolveProjectName?: (projectId: string) => string | null;
    onSessionChanged?: () => void;
    getOutputSequence?: () => number;
    setOutputSequence?: (next: number) => void;
  };

  constructor(deps: {
    store: OutputRouteStore;
    windows: OutputWindowHost;
    discoverDevices: () => OutputDevice[];
    resolveDisplay: (displayId: string) => ResolvedOutputDisplay | null;
    resolveStack?: (stackId: string, projectId: string) => ResolvedOutputStack | null;
    origin: () => string;
    now?: () => string;
    decklink?: DeckLinkEnginePort;
    diskRecording?: DiskRecordingService;
    resolveProjectName?: (projectId: string) => string | null;
    onSessionChanged?: () => void;
    getOutputSequence?: () => number;
    setOutputSequence?: (next: number) => void;
  }) {
    this.deps = deps;
    deps.decklink?.onDeviceLost((deviceId) => this.markEndpointLost(deviceId));
    deps.diskRecording?.setOnChange(() => deps.onSessionChanged?.());
  }

  nextDefaultOutputName(): string {
    return formatDefaultOutputName(this.peekOutputSequence());
  }

  nextDefaultRecordName(projectId: string): string {
    return this.resolveRecordNameForProject(projectId);
  }

  private resolveRecordNameForProject(projectId: string, excludeName?: string): string {
    const existing = this.deps.store
      .list()
      .filter((route) => route.projectId === projectId && route.adapterType === "disk")
      .map((route) => route.name);
    return nextAvailableRecordName(existing, { excludeName });
  }

  private resolveCreateName(input: {
    name?: string;
    projectId: string;
    disk: boolean;
  }): string {
    const trimmed = input.name?.trim() ?? "";
    if (input.disk) {
      if (!trimmed || isAutoGeneratedOutputName(trimmed) || isAutoGeneratedRecordName(trimmed)) {
        return this.resolveRecordNameForProject(input.projectId);
      }
      return trimmed;
    }
    return trimmed || formatDefaultOutputName(this.consumeOutputSequence());
  }

  private peekOutputSequence(): number {
    if (this.deps.getOutputSequence) return Math.max(1, this.deps.getOutputSequence());
    return this.memoryOutputSequence;
  }

  private consumeOutputSequence(): number {
    const current = this.peekOutputSequence();
    const next = current + 1;
    if (this.deps.setOutputSequence) this.deps.setOutputSequence(next);
    else this.memoryOutputSequence = next;
    return current;
  }

  discoverDevices(): OutputDevice[] {
    return [
      ...this.deps.discoverDevices(),
      ...(this.deps.decklink?.discoverDevices() ?? []),
      createDiskRecordingDevice(),
    ];
  }

  diskRecordingCodecs() {
    return this.deps.diskRecording?.codecs() ?? [];
  }

  diskRecordingPlatform() {
    return this.deps.diskRecording?.platform() ?? { encoder: "unavailable", available: false };
  }

  decklinkAvailability(): { sdkAvailable: boolean; sdkVersion: string | null; reason: string | null } {
    return (
      this.deps.decklink?.availability() ?? {
        sdkAvailable: false,
        sdkVersion: null,
        reason: DECKLINK_SDK_UNAVAILABLE,
      }
    );
  }

  list(): OutputRouteView[] {
    const devices = this.discoverDevices();
    return this.deps.store.list().map((route) => this.toView(route, devices));
  }

  diagnostics() {
    return this.list().map((route) => ({
      adapter: route.adapterType,
      deviceId: route.deviceId,
      routeId: route.id,
      projectId: route.projectId,
      displayId: route.displayId,
      sourceType: route.sourceType,
      sourceId: route.sourceId,
      sessionState: route.session.status,
      windowBounds: route.session.windowBounds,
      renderUrl: route.session.renderUrl,
      lastError: route.session.lastError,
      startedAt: route.session.startedAt,
      presentationStrategy: outputPresentationMode(process.platform),
      fullscreenMode: outputPresentationMode(process.platform),
      alwaysOnTop: route.configuration.alwaysOnTop !== false,
      hideCursor: route.configuration.hideCursor !== false,
      outputBackground: COMPUTER_DISPLAY_OUTPUT_BACKGROUND,
      targetDisplayBounds: route.session.windowBounds,
      actualWindowBounds: route.session.windowBounds,
      windowLevel:
        process.platform === "darwin" && route.configuration.alwaysOnTop !== false
          ? "status-plus-one"
          : route.configuration.alwaysOnTop !== false
            ? "floating"
            : "normal",
      visibleOnAllWorkspaces: false,
      isFullScreen: process.platform !== "darwin" && route.session.status === "live",
      hideCursorRequested: route.configuration.hideCursor !== false,
      cursorComputedOuter: route.configuration.hideCursor !== false ? "none" : "auto",
      cursorComputedIframe: route.configuration.hideCursor !== false ? "none" : "auto",
      cursorComputedInner: route.configuration.hideCursor !== false ? "none" : "auto",
      ...(route.adapterType === "decklink" ? { decklink: route.decklink } : {}),
      ...(route.adapterType === "disk"
        ? {
            recording: route.recording,
            recordingFolder: route.configuration.recording?.destinationFolder ?? null,
            recordingFormat: route.configuration.recording?.format ?? null,
            targetFrameRateId: route.configuration.recording?.frameRateId ?? null,
          }
        : {}),
    }));
  }

  hasActiveSession(): boolean {
    for (const session of this.sessions.values()) {
      if (
        session.status === "live" ||
        session.status === "starting" ||
        session.status === "recording" ||
        session.status === "finalizing"
      ) {
        return true;
      }
    }
    return false;
  }

  /** Live, starting, recording, or finalizing outputs from canonical engine sessions. */
  getActiveOutputs(): ActiveOutputSession[] {
    const active: ActiveOutputSession[] = [];
    for (const route of this.list()) {
      const status = route.session.status;
      if (
        status !== "live" &&
        status !== "starting" &&
        status !== "recording" &&
        status !== "finalizing"
      ) {
        continue;
      }
      active.push({
        routeId: route.id,
        name: route.name,
        projectId: route.projectId,
        sourceType: route.sourceType,
        sourceId: route.sourceId,
        status,
        adapterType: route.adapterType,
      });
    }
    return active;
  }

  /** Aggregate tally for global LIVE/REC indicators. */
  getOutputTally() {
    const routes = this.list();
    let liveCount = 0;
    let recordingCount = 0;
    let startingCount = 0;
    let finalizingCount = 0;
    let errorCount = 0;
    for (const route of routes) {
      const status = route.session.status;
      if (status === "error" || status === "device-unavailable") {
        if (route.session.lastError) errorCount += 1;
        continue;
      }
      if (route.adapterType === "disk") {
        if (status === "recording") recordingCount += 1;
        else if (status === "starting") startingCount += 1;
        else if (status === "finalizing") finalizingCount += 1;
        continue;
      }
      if (status === "live") liveCount += 1;
      else if (status === "starting") startingCount += 1;
    }
    return {
      liveCount,
      recordingCount,
      startingCount,
      finalizingCount,
      errorCount,
      hasLive: liveCount > 0,
      hasRecording: recordingCount > 0,
      inactive: liveCount === 0 && recordingCount === 0 && startingCount === 0 && finalizingCount === 0,
    };
  }

  stopRoutes(routeIds: string[]): void {
    for (const routeId of routeIds) {
      const trimmed = routeId.trim();
      if (trimmed) this.stop(trimmed);
    }
  }

  create(input: {
    name?: string;
    projectId: string;
    displayId?: string;
    sourceType?: OutputSourceType;
    sourceId?: string;
    deviceId: string;
    alwaysOnTop?: boolean;
    hideCursor?: boolean;
    displayModeId?: string;
    presentationMode?: "fill" | "keyFill";
    keyDeviceId?: string;
    recording?: Partial<DiskRecordingConfiguration>;
  }): OutputRouteView {
    const now = this.timestamp();
    const device = this.discoverDevices().find((entry) => entry.id === input.deviceId);
    const disk =
      device?.capabilities.kind === "disk" ||
      input.deviceId === DISK_RECORDING_DEVICE_ID ||
      input.deviceId.startsWith("disk:");
    const decklink =
      !disk &&
      (device?.capabilities.kind === "decklink" || input.deviceId.startsWith("decklink:"));
    const source = normalizeOutputRouteSource({
      sourceType: input.sourceType ?? "display",
      sourceId: input.sourceId ?? input.displayId ?? "",
      displayId: input.displayId ?? "",
    });
    const adapterType: OutputAdapterType = disk ? "disk" : decklink ? "decklink" : "display";
    const route: OutputRoute = {
      id: randomUUID(),
      name: this.resolveCreateName({
        name: input.name,
        projectId: input.projectId,
        disk,
      }),
      projectId: input.projectId,
      displayId: source.displayId,
      sourceType: source.sourceType,
      sourceId: source.sourceId,
      adapterType,
      deviceId: disk ? DISK_RECORDING_DEVICE_ID : input.deviceId,
      mode: "borderless",
      enabled: true,
      configuration: disk
        ? withComputerDisplayConfiguration({
            deviceLabel: "Record to Disk",
            deviceWidth: input.recording?.width ?? 1920,
            deviceHeight: input.recording?.height ?? 1080,
            alwaysOnTop: false,
            hideCursor: true,
            recording: normalizeDiskRecordingConfiguration(input.recording),
          })
        : decklink
          ? this.decklinkConfiguration(
              device ?? null,
              input.displayModeId,
              input.alwaysOnTop,
              input.hideCursor,
              undefined,
              input.presentationMode,
              input.keyDeviceId,
            )
          : withComputerDisplayConfiguration({
              electronDisplayId:
                device?.capabilities.kind === "computer-display"
                  ? device.capabilities.electronDisplayId
                  : null,
              deviceLabel: device?.name ?? "",
              deviceWidth: device?.capabilities.width ?? null,
              deviceHeight: device?.capabilities.height ?? null,
              alwaysOnTop: input.alwaysOnTop,
              hideCursor: input.hideCursor,
            }),
      createdAt: now,
      updatedAt: now,
    };
    this.deps.store.save(route);
    return this.toView(route, this.discoverDevices());
  }

  update(
    id: string,
    patch: Partial<
      Pick<OutputRoute, "name" | "projectId" | "displayId" | "deviceId" | "sourceType" | "sourceId">
    > & {
      alwaysOnTop?: boolean;
      hideCursor?: boolean;
      displayModeId?: string;
      presentationMode?: "fill" | "keyFill";
      keyDeviceId?: string;
      recording?: Partial<DiskRecordingConfiguration>;
    },
  ): OutputRouteView | null {
    const existing = this.deps.store.get(id);
    if (!existing) return null;
    const session = this.sessions.get(id);
    const live =
      session?.status === "live" ||
      session?.status === "starting" ||
      session?.status === "recording" ||
      session?.status === "finalizing";
    const nextSource = normalizeOutputRouteSource({
      sourceType: patch.sourceType ?? existing.sourceType,
      sourceId:
        patch.sourceId ??
        (patch.displayId != null && patch.sourceType !== "stack" ? patch.displayId : existing.sourceId),
      displayId: patch.displayId ?? existing.displayId,
    });
    if (live) {
      // Name and computer-display presentation (alwaysOnTop / hideCursor) may change live.
      // Hardware routing (device / display / project / DeckLink video mode) requires Stop.
      const routingChanged =
        (patch.deviceId != null && patch.deviceId !== existing.deviceId) ||
        (patch.displayId != null && patch.displayId !== existing.displayId) ||
        (patch.projectId != null && patch.projectId !== existing.projectId) ||
        (patch.sourceType != null && patch.sourceType !== existing.sourceType) ||
        (patch.sourceId != null && patch.sourceId !== existing.sourceId) ||
        nextSource.sourceType !== existing.sourceType ||
        nextSource.sourceId !== existing.sourceId ||
        (patch.displayModeId != null &&
          patch.displayModeId !== existing.configuration.decklink?.displayModeId) ||
        (patch.recording != null && existing.adapterType === "disk");
      if (routingChanged) {
        throw new Error(LIVE_ROUTING_EDIT_BLOCKED);
      }
    }
    const device = patch.deviceId
      ? this.discoverDevices().find((entry) => entry.id === patch.deviceId)
      : this.resolveDevice(existing, this.discoverDevices());
    const disk =
      device?.capabilities.kind === "disk" ||
      (!device && existing.adapterType === "disk") ||
      existing.adapterType === "disk";
    const decklink =
      !disk &&
      ((device?.capabilities.kind === "decklink") || (!device && existing.adapterType === "decklink"));
    const next: OutputRoute = {
      ...existing,
      ...patch,
      displayId: nextSource.displayId,
      sourceType: nextSource.sourceType,
      sourceId: nextSource.sourceId,
      adapterType: disk ? "disk" : decklink ? "decklink" : "display",
      deviceId: disk ? DISK_RECORDING_DEVICE_ID : patch.deviceId ?? existing.deviceId,
      name: patch.name?.trim() || existing.name,
      configuration: disk
        ? withComputerDisplayConfiguration({
            ...existing.configuration,
            deviceLabel: "Record to Disk",
            recording: normalizeDiskRecordingConfiguration({
              ...existing.configuration.recording,
              ...patch.recording,
            }),
            alwaysOnTop: false,
            hideCursor: true,
          })
        : decklink
          ? this.decklinkConfiguration(
              device?.capabilities.kind === "decklink" ? device : null,
              patch.displayModeId ?? existing.configuration.decklink?.displayModeId,
              patch.alwaysOnTop ?? existing.configuration.alwaysOnTop,
              patch.hideCursor ?? existing.configuration.hideCursor,
              existing.configuration,
              patch.presentationMode ?? existing.configuration.decklink?.presentationMode,
              patch.keyDeviceId ?? existing.configuration.decklink?.keyEndpointId ?? undefined,
            )
          : withComputerDisplayConfiguration({
              ...existing.configuration,
              ...(device?.capabilities.kind === "computer-display"
                ? {
                    electronDisplayId: device.capabilities.electronDisplayId,
                    deviceLabel: device.name,
                    deviceWidth: device.capabilities.width,
                    deviceHeight: device.capabilities.height,
                  }
                : {}),
              alwaysOnTop: patch.alwaysOnTop ?? existing.configuration.alwaysOnTop,
              hideCursor: patch.hideCursor ?? existing.configuration.hideCursor,
            }),
      updatedAt: this.timestamp(),
    };
    this.deps.store.save(next);
    if (
      session &&
      (session.status === "live" || session.status === "starting") &&
      next.adapterType === "display" &&
      session.windowBounds &&
      this.deps.windows.reconfigure
    ) {
      this.deps.windows.reconfigure({
        routeId: id,
        bounds: session.windowBounds,
        alwaysOnTop: next.configuration.alwaysOnTop,
        hideCursor: next.configuration.hideCursor,
        platform: process.platform,
      });
    }
    return this.toView(next, this.discoverDevices());
  }

  delete(id: string): void {
    this.stop(id);
    this.sessions.delete(id);
    this.deps.store.delete(id);
  }

  async start(id: string, options?: { confirmPrimary?: boolean }) {
    const route = this.deps.store.get(id);
    if (!route) {
      return { ok: false as const, code: "missing-route", error: "Output route was not found.", route: null };
    }
    const devices = this.discoverDevices();
    if (route.adapterType === "disk") {
      return this.startDiskRecording(id, route, devices);
    }
    const device = this.resolveDevice(route, devices);
    if (!device) {
      const decklinkRoute = route.adapterType === "decklink";
      const error = decklinkRoute ? DECKLINK_DEVICE_UNAVAILABLE : "Selected monitor is disconnected";
      this.setSession(id, {
        ...stoppedSession(id, error),
        status: "device-unavailable",
      });
      return {
        ok: false as const,
        code: "device-unavailable",
        error,
        route: this.toView(route, devices),
      };
    }
    if (device.capabilities.kind === "decklink") {
      return this.startDeckLink(id, route, device, devices);
    }
    if (device.primary && !options?.confirmPrimary) {
      return {
        ok: false as const,
        code: "primary-warning",
        error: PRIMARY_MONITOR_WARNING,
        route: this.toView(route, devices),
      };
    }
    const source = this.resolveRouteSource(route);
    if (!source.ok) {
      this.setSession(id, {
        ...stoppedSession(id, source.error),
        status: "error",
      });
      return {
        ok: false as const,
        code: source.code,
        error: source.error,
        route: this.toView(route, devices),
      };
    }
    const occupied = [...this.sessions.entries()].some(([routeId, session]) => {
      if (routeId === id) return false;
      if (session.status !== "live" && session.status !== "starting") return false;
      return this.deps.store.get(routeId)?.deviceId === device.id;
    });
    if (occupied) {
      return {
        ok: false as const,
        code: "device-busy",
        error: "That monitor already has a live output.",
        route: this.toView(route, devices),
      };
    }
    const bounds = device.capabilities.bounds;
    const presentation = withComputerDisplayConfiguration(route.configuration);
    const renderUrl =
      source.kind === "stack"
        ? buildOutputStackRenderUrl({
            origin: this.deps.origin(),
            projectId: source.stack.projectId,
            stackId: source.stack.stackId,
            layers: source.stack.layers.map((layer) => ({
              displayId: layer.displayId,
              slug: layer.slug,
              zIndex: layer.zIndex,
              width: layer.width,
              height: layer.height,
            })),
            authoredWidth: source.stack.width,
            authoredHeight: source.stack.height,
            surface: "computer",
            hideCursor: presentation.hideCursor,
            outputWidth: bounds.width,
            outputHeight: bounds.height,
          })
        : buildOutputRenderUrl({
            origin: this.deps.origin(),
            projectId: source.display.projectId,
            slug: source.display.slug,
            authoredWidth: source.display.width,
            authoredHeight: source.display.height,
            outputWidth: bounds.width,
            outputHeight: bounds.height,
            hideCursor: presentation.hideCursor,
          });
    this.setSession(id, {
      routeId: id,
      status: "starting",
      startedAt: null,
      lastError: null,
      renderUrl,
      windowBounds: bounds,
    });
    const opened = await this.deps.windows.open({
      routeId: id,
      url: renderUrl,
      bounds,
      background: presentation.background,
      alwaysOnTop: presentation.alwaysOnTop,
      hideCursor: presentation.hideCursor,
      primary: device.primary,
      platform: process.platform,
    });
    if (!opened.ok) {
      this.deps.windows.close(id);
      this.setSession(id, {
        ...stoppedSession(id, opened.error || "Output window failed to launch"),
        status: "error",
      });
      return {
        ok: false as const,
        code: "window-failed",
        error: opened.error || "Output window failed to launch",
        route: this.toView(route, devices),
      };
    }
    this.setSession(id, {
      routeId: id,
      status: "live",
      startedAt: this.timestamp(),
      lastError: null,
      renderUrl,
      windowBounds: bounds,
    });
    const refreshed = this.rebindDevice(route, device);
    return { ok: true as const, route: this.toView(refreshed, this.discoverDevices()) };
  }

  stop(id: string): OutputRouteView | null {
    const route = this.deps.store.get(id);
    if (route?.adapterType === "disk") {
      this.setSession(id, {
        routeId: id,
        status: "finalizing",
        startedAt: this.sessions.get(id)?.startedAt ?? null,
        lastError: null,
        renderUrl: this.sessions.get(id)?.renderUrl ?? null,
        windowBounds: null,
      });
      void this.deps.diskRecording?.stop(id).then((result) => {
        this.setSession(
          id,
          stoppedSession(id, result.ok ? null : result.error),
        );
        if (!result.ok) {
          this.setSession(id, {
            ...stoppedSession(id, result.error),
            status: "error",
          });
        }
      });
      return this.toView(route, this.discoverDevices());
    }
    this.deps.windows.close(id);
    this.deps.decklink?.stop(id);
    this.setSession(id, stoppedSession(id));
    return route ? this.toView(route, this.discoverDevices()) : null;
  }

  async restart(id: string, options?: { confirmPrimary?: boolean }) {
    this.stop(id);
    return this.start(id, options);
  }

  refreshDevices(): void {
    const devices = this.discoverDevices();
    for (const route of this.deps.store.list()) {
      const session = this.sessions.get(route.id);
      if (!session || (session.status !== "live" && session.status !== "starting")) continue;
      const device = this.resolveDevice(route, devices);
      if (!device) {
        this.deps.windows.close(route.id);
        this.deps.decklink?.stop(route.id);
        this.setSession(route.id, {
          routeId: route.id,
          status: "device-unavailable",
          startedAt: session.startedAt,
          lastError: route.adapterType === "decklink" ? DECKLINK_DEVICE_REMOVED : "Selected monitor is disconnected",
          renderUrl: null,
          windowBounds: null,
        });
        continue;
      }
      this.rebindDevice(route, device);
    }
  }

  stopAll(): void {
    for (const route of this.deps.store.list()) this.stop(route.id);
  }

  private resolveDevice(route: OutputRoute, devices: OutputDevice[]) {
    if (route.adapterType === "disk") {
      return devices.find((device) => device.adapterType === "disk") ?? createDiskRecordingDevice();
    }
    if (route.adapterType === "decklink") return matchDeckLinkDevice(route, devices);
    return matchStoredDevice(
      route.deviceId,
      devices,
      route.configuration.electronDisplayId,
      route.configuration.deviceLabel,
      route.configuration.deviceWidth,
      route.configuration.deviceHeight,
    );
  }

  private async startDiskRecording(
    id: string,
    route: OutputRoute,
    devices: OutputDevice[],
  ) {
    if (!this.deps.diskRecording) {
      this.setSession(id, {
        ...stoppedSession(id, "Disk recording service is unavailable."),
        status: "error",
      });
      return {
        ok: false as const,
        code: "encoder-unavailable",
        error: "Disk recording service is unavailable.",
        route: this.toView(route, devices),
      };
    }
    const source = this.resolveRouteSource(route);
    if (!source.ok) {
      this.setSession(id, {
        ...stoppedSession(id, source.error),
        status: "error",
      });
      return {
        ok: false as const,
        code: source.code,
        error: source.error,
        route: this.toView(route, devices),
      };
    }
    const recording = normalizeDiskRecordingConfiguration(route.configuration.recording);
    const renderUrl =
      source.kind === "stack"
        ? buildOutputStackRenderUrl({
            origin: this.deps.origin(),
            projectId: source.stack.projectId,
            stackId: source.stack.stackId,
            layers: source.stack.layers.map((layer) => ({
              displayId: layer.displayId,
              slug: layer.slug,
              zIndex: layer.zIndex,
              width: layer.width,
              height: layer.height,
            })),
            authoredWidth: source.stack.width,
            authoredHeight: source.stack.height,
            surface: "decklink",
            hideCursor: true,
            outputWidth: recording.width,
            outputHeight: recording.height,
          })
        : buildOutputRenderUrl({
            origin: this.deps.origin(),
            projectId: source.display.projectId,
            slug: source.display.slug,
            authoredWidth: source.display.width,
            authoredHeight: source.display.height,
            outputWidth: recording.width,
            outputHeight: recording.height,
            hideCursor: true,
          });
    this.setSession(id, {
      routeId: id,
      status: "starting",
      startedAt: null,
      lastError: null,
      renderUrl,
      windowBounds: null,
    });
    const projectName =
      this.deps.resolveProjectName?.(route.projectId) ??
      (source.kind === "display" ? source.display.projectName : route.projectId);
    const started = await this.deps.diskRecording.start({
      routeId: id,
      projectId: route.projectId,
      projectName,
      outputName: route.name,
      renderUrl,
      configuration: recording,
    });
    if (!started.ok) {
      this.setSession(id, {
        ...stoppedSession(id, started.error),
        status: "error",
      });
      return {
        ok: false as const,
        code: started.code,
        error: started.error,
        route: this.toView(route, devices),
      };
    }
    this.setSession(id, {
      routeId: id,
      status: "recording",
      startedAt: started.metrics.startedAt,
      lastError: null,
      renderUrl,
      windowBounds: null,
    });
    return { ok: true as const, route: this.toView(route, devices) };
  }

  private rebindDevice(route: OutputRoute, device: OutputDevice): OutputRoute {
    if (device.capabilities.kind === "disk") {
      return route;
    }
    const next: OutputRoute = {
      ...route,
      deviceId: device.id,
      configuration:
        device.capabilities.kind === "decklink"
          ? this.decklinkConfiguration(
              device,
              route.configuration.decklink?.displayModeId,
              route.configuration.alwaysOnTop,
              route.configuration.hideCursor,
              route.configuration,
            )
          : {
              ...route.configuration,
              electronDisplayId: device.capabilities.electronDisplayId,
              deviceLabel: device.name,
              deviceWidth: device.capabilities.width,
              deviceHeight: device.capabilities.height,
            },
      updatedAt: this.timestamp(),
    };
    this.deps.store.save(next);
    return next;
  }

  private toView(route: OutputRoute, devices: OutputDevice[]): OutputRouteView {
    const device = this.resolveDevice(route, devices);
    const normalized = normalizeOutputRouteSource(route);
    const session = this.sessions.get(route.id) ?? stoppedSession(route.id);
    let displayName: string | null = null;
    let sourceAvailable = true;
    if (normalized.sourceType === "stack") {
      const stack = this.deps.resolveStack?.(normalized.sourceId, route.projectId) ?? null;
      if (!stack || stack.projectId !== route.projectId || stack.layers.length < 2) {
        displayName = STACK_UNAVAILABLE_FOR_OUTPUT;
        sourceAvailable = false;
      } else {
        displayName = stack.stackName;
      }
    } else {
      const display = this.deps.resolveDisplay(normalized.sourceId || route.displayId);
      displayName = display?.displayName ?? null;
      sourceAvailable = Boolean(display && display.projectId === route.projectId);
    }
    return {
      ...route,
      displayId: normalized.displayId,
      sourceType: normalized.sourceType,
      sourceId: normalized.sourceId,
      session,
      deviceName:
        device?.name ??
        (route.configuration.decklink
          ? formatExternalPortLabel(
              route.configuration.decklink.modelName,
              route.configuration.decklink.endpointIndex,
            )
          : route.configuration.deviceLabel || null),
      displayName,
      resolutionLabel:
        route.adapterType === "decklink" && route.configuration.decklink
          ? `${route.configuration.decklink.width}×${route.configuration.decklink.height}`
          : device
            ? `${device.capabilities.width}×${device.capabilities.height}`
            : null,
      primaryWarning: Boolean(device?.primary),
      decklink: route.adapterType === "decklink" ? this.deps.decklink?.metrics(route.id) ?? null : null,
      recording:
        route.adapterType === "disk"
          ? this.deps.diskRecording?.getMetrics(route.id) ??
            (route.configuration.recording
              ? {
                  lifecycle:
                    session.status === "recording"
                      ? "recording"
                      : session.status === "starting"
                        ? "starting"
                        : session.status === "finalizing"
                          ? "finalizing"
                          : session.status === "error"
                            ? "error"
                            : "idle",
                  startedAt: session.startedAt,
                  durationSeconds: 0,
                  outputPath: null,
                  tempPath: null,
                  byteSize: 0,
                  droppedFrames: 0,
                  encodedFrames: 0,
                  actualFps: null,
                  writeBytesPerSecond: null,
                  availableDiskBytes: null,
                  format: route.configuration.recording.format,
                  supportsAlpha: route.configuration.recording.alphaMode === "preserve",
                  lastError: session.lastError,
                }
              : null)
          : null,
      sourceAvailable,
    };
  }

  private resolveRouteSource(route: OutputRoute):
    | { ok: true; kind: "display"; display: ResolvedOutputDisplay }
    | { ok: true; kind: "stack"; stack: ResolvedOutputStack }
    | {
        ok: false;
        code: "missing-display" | "display-disabled" | "stack-unavailable";
        error: string;
      } {
    const normalized = normalizeOutputRouteSource(route);
    if (normalized.sourceType === "stack") {
      const stack = this.deps.resolveStack?.(normalized.sourceId, route.projectId) ?? null;
      if (!stack || stack.projectId !== route.projectId || stack.layers.length < 2) {
        return {
          ok: false,
          code: "stack-unavailable",
          error: STACK_UNAVAILABLE_FOR_OUTPUT,
        };
      }
      return { ok: true, kind: "stack", stack };
    }
    const display = this.deps.resolveDisplay(normalized.sourceId || route.displayId);
    if (!display || display.projectId !== route.projectId) {
      return {
        ok: false,
        code: "missing-display",
        error: "Display could not be resolved",
      };
    }
    if (!display.enabled) {
      return {
        ok: false,
        code: "display-disabled",
        error: DISPLAY_DISABLED_FOR_OUTPUT,
      };
    }
    return { ok: true, kind: "display", display };
  }

  private releaseRouteOutput(routeId: string): void {
    this.deps.windows.close(routeId);
    this.deps.decklink?.stop(routeId);
  }

  private markEndpointLost(deviceId: string): void {
    for (const route of this.deps.store.list()) {
      if (route.adapterType !== "decklink") continue;
      const session = this.sessions.get(route.id);
      if (!session || (session.status !== "live" && session.status !== "starting")) continue;
      const matches =
        route.deviceId === deviceId || route.configuration.decklink?.outputEndpointId === deviceId;
      if (!matches) continue;
      this.releaseRouteOutput(route.id);
      this.setSession(route.id, {
        routeId: route.id,
        status: "device-unavailable",
        startedAt: session.startedAt,
        lastError: DECKLINK_DEVICE_REMOVED,
        renderUrl: session.renderUrl,
        windowBounds: session.windowBounds,
      });
    }
  }

  /**
   * Live Key + Fill (and Fill) routes reserve every physical endpoint they use.
   * Returns an operator-facing busy message, or null when free.
   */
  private findOccupiedEndpointConflict(exceptRouteId: string, endpointIds: Array<string | null>): string | null {
    const wanted = new Set(endpointIds.filter((id): id is string => Boolean(id)));
    if (wanted.size === 0) return null;
    for (const [routeId, session] of this.sessions.entries()) {
      if (routeId === exceptRouteId) continue;
      if (session.status !== "live" && session.status !== "starting") continue;
      const other = this.deps.store.get(routeId);
      if (!other) continue;
      const used = [other.deviceId, other.configuration.decklink?.keyEndpointId ?? null].filter(
        (id): id is string => Boolean(id),
      );
      const conflictId = used.find((id) => wanted.has(id));
      if (!conflictId) continue;
      const conflictDevice = this.discoverDevices().find((device) => device.id === conflictId);
      const label =
        conflictDevice?.capabilities.kind === "decklink"
          ? formatExternalPortLabel(
              conflictDevice.capabilities.modelName,
              conflictDevice.capabilities.endpointIndex,
            )
          : conflictDevice?.name ?? conflictId;
      return `${label} is already in use by ${other.name}`;
    }
    return null;
  }

  private decklinkConfiguration(
    device: OutputDevice | null,
    displayModeId: string | undefined,
    alwaysOnTop: boolean | undefined,
    hideCursor: boolean | undefined,
    previous?: OutputRoute["configuration"],
    presentationMode?: "fill" | "keyFill",
    keyDeviceId?: string,
  ): OutputRoute["configuration"] {
    const base = withComputerDisplayConfiguration({
      ...previous,
      deviceLabel: device?.name ?? previous?.deviceLabel ?? "",
      deviceWidth: device?.capabilities.width ?? previous?.deviceWidth ?? null,
      deviceHeight: device?.capabilities.height ?? previous?.deviceHeight ?? null,
      alwaysOnTop,
      hideCursor,
      electronDisplayId: null,
    });
    const capabilities = device?.capabilities.kind === "decklink" ? device.capabilities : null;
    const saved = previous?.decklink;
    const requested = displayModeId ?? saved?.displayModeId ?? "";
    const mode = requested
      ? capabilities?.modes.find((entry) => entry.id === requested) ?? null
      : capabilities?.modes[0] ?? null;
    const modeValue = presentationMode ?? saved?.presentationMode ?? "fill";
    const transport =
      modeValue === "keyFill"
        ? (capabilities?.external?.keyFillTransport ?? saved?.keyFillTransport ?? undefined)
        : undefined;
    const decklink: DeckLinkRouteConfiguration | undefined = capabilities
      ? {
          outputEndpointId: device?.id ?? saved?.outputEndpointId ?? "",
          persistentId: capabilities.persistentId,
          modelName: capabilities.modelName,
          endpointName: capabilities.endpointName,
          endpointIndex: capabilities.endpointIndex,
          displayModeId: mode?.id ?? requested,
          modeName: mode?.name ?? saved?.modeName ?? "",
          pixelFormat: DECKLINK_FILL_PIXEL_FORMAT,
          fillBackground: saved?.fillBackground || DECKLINK_FILL_BACKGROUND,
          frameRateNumerator: mode?.frameRateNumerator ?? saved?.frameRateNumerator ?? 0,
          frameRateDenominator: mode?.frameRateDenominator ?? saved?.frameRateDenominator ?? 1,
          width: mode?.width ?? saved?.width ?? capabilities.width,
          height: mode?.height ?? saved?.height ?? capabilities.height,
          presentationMode: modeValue,
          keyFillTransport: transport,
          keyEndpointId:
            modeValue === "keyFill" && transport === "pairedPorts"
              ? keyDeviceId ?? saved?.keyEndpointId ?? null
              : null,
          sourceAlphaMode: "premultiplied",
          deckLinkFrameAlphaMode: modeValue === "keyFill" ? "straight" : undefined,
          fillAlphaMode: modeValue === "keyFill" ? "premultiplied" : "blackComposite",
          keyPolarity: "whiteOnBlack",
        }
      : saved;
    return decklink ? { ...base, decklink } : base;
  }

  private async startDeckLink(
    id: string,
    route: OutputRoute,
    device: OutputDevice,
    devices: OutputDevice[],
  ) {
    if (device.capabilities.kind !== "decklink") {
      return {
        ok: false as const,
        code: "device-unavailable",
        error: DECKLINK_DEVICE_UNAVAILABLE,
        route: this.toView(route, devices),
      };
    }
    if (!device.available) {
      this.setSession(id, {
        ...stoppedSession(id, DECKLINK_DEVICE_UNAVAILABLE),
        status: "device-unavailable",
      });
      return {
        ok: false as const,
        code: "device-unavailable",
        error: DECKLINK_DEVICE_UNAVAILABLE,
        route: this.toView(route, devices),
      };
    }
    const presentationMode = route.configuration.decklink?.presentationMode ?? "fill";
    const keyFillTransport =
      route.configuration.decklink?.keyFillTransport ??
      (device.capabilities.kind === "decklink"
        ? device.capabilities.external?.keyFillTransport ?? null
        : null);
    if (presentationMode === "keyFill") {
      if (keyFillTransport === "pairedPorts") {
        this.setSession(id, {
          ...stoppedSession(id, KEY_FILL_NOT_IMPLEMENTED),
          status: "error",
        });
        return {
          ok: false as const,
          code: "key-fill-not-implemented",
          error: KEY_FILL_NOT_IMPLEMENTED,
          route: this.toView(route, devices),
        };
      }
      if (keyFillTransport !== "nativeExternalKey") {
        this.setSession(id, {
          ...stoppedSession(id, KEY_FILL_TRANSPORT_UNSUPPORTED),
          status: "error",
        });
        return {
          ok: false as const,
          code: "key-fill-unsupported",
          error: KEY_FILL_TRANSPORT_UNSUPPORTED,
          route: this.toView(route, devices),
        };
      }
    }
    const occupiedEndpoint = this.findOccupiedEndpointConflict(id, [
      device.id,
      // nativeExternalKey reserves the one logical endpoint (hardware owns Fill+Key pair).
      presentationMode === "keyFill" && keyFillTransport === "pairedPorts"
        ? route.configuration.decklink?.keyEndpointId ?? null
        : null,
    ]);
    if (occupiedEndpoint) {
      return {
        ok: false as const,
        code: "device-busy",
        error: occupiedEndpoint,
        route: this.toView(route, devices),
      };
    }
    const modeId = route.configuration.decklink?.displayModeId ?? "";
    const mode = device.capabilities.modes.find((entry) => entry.id === modeId);
    if (!mode) {
      this.setSession(id, {
        ...stoppedSession(id, DECKLINK_MODE_UNSUPPORTED),
        status: "error",
      });
      return {
        ok: false as const,
        code: "mode-unavailable",
        error: DECKLINK_MODE_UNSUPPORTED,
        route: this.toView(route, devices),
      };
    }
    if (!mode.pixelFormats.includes(DECKLINK_FILL_PIXEL_FORMAT)) {
      this.setSession(id, {
        ...stoppedSession(id, DECKLINK_PIXEL_FORMAT_UNSUPPORTED),
        status: "error",
      });
      return {
        ok: false as const,
        code: "pixel-format-unsupported",
        error: DECKLINK_PIXEL_FORMAT_UNSUPPORTED,
        route: this.toView(route, devices),
      };
    }
    const source = this.resolveRouteSource(route);
    if (!source.ok) {
      this.setSession(id, {
        ...stoppedSession(id, source.error),
        status: "error",
      });
      return {
        ok: false as const,
        code: source.code,
        error: source.error,
        route: this.toView(route, devices),
      };
    }
    if (!this.deps.decklink) {
      this.setSession(id, { ...stoppedSession(id, EXTERNAL_DEVICE_SUPPORT_UNAVAILABLE), status: "error" });
      return {
        ok: false as const,
        code: "sdk-unavailable",
        error: EXTERNAL_DEVICE_SUPPORT_UNAVAILABLE,
        route: this.toView(route, devices),
      };
    }
    const renderUrl =
      source.kind === "stack"
        ? buildOutputStackRenderUrl({
            origin: this.deps.origin(),
            projectId: source.stack.projectId,
            stackId: source.stack.stackId,
            layers: source.stack.layers.map((layer) => ({
              displayId: layer.displayId,
              slug: layer.slug,
              zIndex: layer.zIndex,
              width: layer.width,
              height: layer.height,
            })),
            authoredWidth: source.stack.width,
            authoredHeight: source.stack.height,
            surface: "decklink",
            outputWidth: mode.width,
            outputHeight: mode.height,
          })
        : buildDeckLinkRenderUrl({
            origin: this.deps.origin(),
            projectId: source.display.projectId,
            slug: source.display.slug,
            authoredWidth: source.display.width,
            authoredHeight: source.display.height,
            targetWidth: mode.width,
            targetHeight: mode.height,
          });
    const authoredWidth = source.kind === "stack" ? source.stack.width : source.display.width;
    const authoredHeight = source.kind === "stack" ? source.stack.height : source.display.height;
    const windowBounds = { x: 0, y: 0, width: mode.width, height: mode.height };
    this.setSession(id, {
      routeId: id,
      status: "starting",
      startedAt: null,
      lastError: null,
      renderUrl,
      windowBounds,
    });
    const started = await this.deps.decklink.start({
      routeId: id,
      routeName: route.name,
      device,
      displayModeId: mode.id,
      fillBackground: route.configuration.decklink?.fillBackground || DECKLINK_FILL_BACKGROUND,
      renderUrl,
      authoredWidth,
      authoredHeight,
      presentationMode,
    });
    const current = this.sessions.get(id);
    if (!current || current.status !== "starting") {
      this.deps.decklink.stop(id);
      return {
        ok: false as const,
        code: "stopped",
        error: current?.lastError || "Output stopped",
        route: this.toView(route, this.discoverDevices()),
      };
    }
    if (!started.ok) {
      this.deps.decklink.stop(id);
      const unavailable = started.code === "device-unavailable" || started.code === "device-removed";
      const stageError = started.nativeError ? `${started.error} (${started.nativeError})` : started.error;
      this.setSession(id, {
        ...stoppedSession(id, stageError),
        status: unavailable ? "device-unavailable" : "error",
        renderUrl,
        windowBounds,
      });
      return {
        ok: false as const,
        code: started.code,
        error: stageError,
        route: this.toView(route, this.discoverDevices()),
      };
    }
    this.setSession(id, {
      routeId: id,
      status: "live",
      startedAt: this.timestamp(),
      lastError: null,
      renderUrl,
      windowBounds,
    });
    const refreshed = this.rebindDevice(route, device);
    return { ok: true as const, route: this.toView(refreshed, this.discoverDevices()) };
  }

  private setSession(routeId: string, session: OutputSession) {
    this.sessions.set(routeId, session);
    try {
      this.deps.onSessionChanged?.();
    } catch {
      // ignore listener errors
    }
  }

  private timestamp(): string {
    return this.deps.now?.() ?? new Date().toISOString();
  }
}

export class MemoryOutputRouteStore implements OutputRouteStore {
  private readonly routes = new Map<string, OutputRoute>();
  list() {
    return [...this.routes.values()].map((route) => {
      const source = normalizeOutputRouteSource(route);
      return { ...route, ...source };
    });
  }
  get(id: string) {
    const route = this.routes.get(id);
    if (!route) return null;
    const source = normalizeOutputRouteSource(route);
    return { ...route, ...source };
  }
  save(route: OutputRoute) {
    const source = normalizeOutputRouteSource(route);
    this.routes.set(route.id, { ...route, ...source });
  }
  delete(id: string) {
    this.routes.delete(id);
  }
}
