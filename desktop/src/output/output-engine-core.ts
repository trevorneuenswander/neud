export function normalizeDisplayLabel(label: string): string {
  const trimmed = label.trim().toLowerCase().replace(/\s+/g, "-");
  return trimmed || "display";
}

export function computerDisplayDeviceId(display: ComputerDisplaySource): string {
  return `display:${display.id}:${normalizeDisplayLabel(display.label)}:${display.size.width}x${display.size.height}`;
}

export function serializeOutputDevice(device: OutputDevice) {
  if (device.capabilities.kind === "decklink") {
    const capabilities = device.capabilities;
    return {
      id: device.id,
      adapterType: device.adapterType,
      name: device.name,
      available: device.available,
      primary: false,
      capabilities: {
        kind: "decklink" as const,
        persistentId: capabilities.persistentId,
        modelName: capabilities.modelName,
        endpointName: capabilities.endpointName,
        endpointIndex: capabilities.endpointIndex,
        width: capabilities.width,
        height: capabilities.height,
        modes: capabilities.modes.map((mode) => ({ ...mode })),
        external: capabilities.external ? { ...capabilities.external } : undefined,
      },
    };
  }
  if (device.capabilities.kind === "disk") {
    const capabilities = device.capabilities;
    return {
      id: device.id,
      adapterType: "disk" as const,
      name: device.name,
      available: device.available,
      primary: false,
      capabilities: {
        kind: "disk" as const,
        width: capabilities.width,
        height: capabilities.height,
        refreshRate: capabilities.refreshRate,
        bounds: { ...capabilities.bounds },
        workArea: { ...capabilities.workArea },
        scaleFactor: capabilities.scaleFactor,
        rotation: capabilities.rotation,
        internal: capabilities.internal,
        electronDisplayId: capabilities.electronDisplayId,
      },
    };
  }
  const capabilities = device.capabilities;
  return {
    id: device.id,
    adapterType: device.adapterType,
    name: device.name,
    available: device.available,
    primary: device.primary,
    capabilities: {
      kind: "computer-display" as const,
      electronDisplayId: capabilities.electronDisplayId,
      width: capabilities.width,
      height: capabilities.height,
      refreshRate: capabilities.refreshRate,
      bounds: { ...capabilities.bounds },
      workArea: { ...capabilities.workArea },
      scaleFactor: capabilities.scaleFactor,
      rotation: capabilities.rotation,
      internal: capabilities.internal,
    },
  };
}

