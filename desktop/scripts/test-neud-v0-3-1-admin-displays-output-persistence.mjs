test("runtime: Record to Disk → Computer Display persists adapterType and renames", async () => {
  // Load TypeScript sources directly (Node 22 strip-types) — not a production package build.
  const coreUrl = pathToFileURL(
    path.join(desktopRoot, "src/output/output-engine-core.ts"),
  ).href;
  const { OutputEngine, MemoryOutputRouteStore } = await import(coreUrl);
  const devices = [
    {
      id: "display:1",
      adapterType: "display",
      name: "Monitor 1",
      available: true,
      primary: true,
      capabilities: {
        kind: "computer-display",
        electronDisplayId: 1,
        width: 1920,
        height: 1080,
        refreshRate: 60,
      },
    },
  ];
  const engine = new OutputEngine({
    store: new MemoryOutputRouteStore(),
    windows: { async open() { return { ok: true }; }, close() {} },
    discoverDevices: () => devices,
    resolveDisplay: () => ({
      projectId: "proj-1",
      displayId: "disp-1",
      name: "Stream Bid",
      width: 1920,
      height: 1080,
      url: "http://127.0.0.1:3000/d/x",
    }),
    origin: () => "http://127.0.0.1:3000",
  });
  const created = engine.create({
    name: "Record 1",
    projectId: "proj-1",
    displayId: "disp-1",
    deviceId: "disk:local",
    recording: {
      format: "h264-mp4",
      destinationFolder: "/tmp/neud-recordings",
      width: 1920,
      height: 1080,
      frameRateId: "29.97",
      alphaMode: "flatten",
      backgroundColor: "#000000",
    },
  });
  assert.equal(created.adapterType, "disk");
  const updated = engine.update(created.id, {
    name: "Record 1",
    deviceId: "display:1",
    alwaysOnTop: true,
    hideCursor: true,
  });
  assert.ok(updated);
  assert.equal(updated.adapterType, "display");
  assert.equal(updated.deviceId, "display:1");
  assert.match(updated.name, /^Output \d+$/);
  assert.equal(updated.configuration.recording, undefined);

  const back = engine.update(updated.id, {
    name: updated.name,
    deviceId: "disk:local",
    recording: {
      format: "h264-mp4",
      destinationFolder: "/tmp/neud-recordings",
      width: 1920,
      height: 1080,
      frameRateId: "29.97",
      alphaMode: "flatten",
      backgroundColor: "#000000",
    },
  });
  assert.equal(back.adapterType, "disk");
  assert.match(back.name, /^Record \d+$/);

  const custom = engine.create({
    name: "Show Feed",
    projectId: "proj-1",
    displayId: "disp-1",
    deviceId: "disk:local",
    recording: {
      format: "h264-mp4",
      destinationFolder: "/tmp/neud-recordings",
      width: 1920,
      height: 1080,
      frameRateId: "29.97",
      alphaMode: "flatten",
      backgroundColor: "#000000",
    },
  });
  const customOut = engine.update(custom.id, {
    name: "Show Feed",
    deviceId: "display:1",
  });
  assert.equal(customOut.name, "Show Feed");
  assert.equal(customOut.adapterType, "display");
});
