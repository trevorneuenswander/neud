import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const desktopRoot = path.join(root, "desktop");

function read(relativePath) {
  return fs.readFileSync(path.join(root, relativePath), "utf8");
}

test("Broad Arrow Displays page always loads developer displays for card build", () => {
  const page = read("src/app/(portal)/projects/[slug]/displays/page.tsx");
  assert.match(
    page,
    /Always load them for Broad Arrow; canManageSettings only gates Archived\/Add controls/,
  );
  assert.match(page, /\[Displays\]\[BroadArrowPage\]/);
  // Must not gate Broad Arrow developerDisplays on canManageSettings.
  const broadArrowBlock = page.slice(
    page.indexOf("if (isBroadArrow)"),
    page.indexOf("try {", page.indexOf("if (isBroadArrow)")),
  );
  assert.doesNotMatch(
    broadArrowBlock,
    /developerDisplays = access\.canManageSettings/,
  );
});

test("DeveloperTools listDisplays uses view access + AccessAuthorizationService", () => {
  const service = read("desktop/src/services/developer-tools-service.ts");
  assert.match(service, /setAccessAuthorization/);
  assert.match(service, /assertCanListDisplays/);
  assert.match(service, /canViewDisplays/);
  assert.match(service, /listDisplays\(projectSlug/);
  const listStart = service.indexOf("listDisplays(projectSlug");
  const listSlice = service.slice(listStart, listStart + 800);
  assert.match(listSlice, /assertCanListDisplays/);
  assert.doesNotMatch(listSlice, /assertDeveloperToolsAccess\(project\.id\)/);
  const main = read("desktop/src/main.ts");
  assert.match(main, /developerToolsService\.setAccessAuthorization\(accessAuthorizationService\)/);
});

test("OutputEngine update does not sticky-keep disk adapterType", () => {
  const engine = read("desktop/src/output/output-engine-core.ts");
  assert.match(engine, /never sticky on existing\.adapterType/);
  assert.match(engine, /nextDeviceId === DISK_RECORDING_DEVICE_ID/);
  assert.doesNotMatch(
    engine,
    /existing\.adapterType === "disk";\s*const decklink/,
  );
  assert.match(engine, /leavingDisk && isAutoGeneratedRecordName/);
  assert.match(engine, /becomingDisk && isAutoGeneratedOutputName/);
});

