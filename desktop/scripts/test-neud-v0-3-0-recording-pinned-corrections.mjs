function createEngine(input = {}) {
  const store = input.store ?? new MemoryOutputRouteStore();
  const diskRecording = input.diskRecording ?? {
    codecs: () => [],
    platform: () => ({ encoder: "test", available: true }),
    setOnChange: () => {},
    getMetrics: () => null,
    start: async () => ({
      ok: true,
      metrics: {
        lifecycle: "recording",
        startedAt: new Date().toISOString(),
        durationSeconds: 0,
        outputPath: null,
        tempPath: null,
        byteSize: 0,
        droppedFrames: 0,
        encodedFrames: 0,
        actualFps: null,
        writeBytesPerSecond: null,
        availableDiskBytes: null,
        format: "prores-4444-mov",
        supportsAlpha: true,
        lastError: null,
      },
    }),
    stop: async () => ({ ok: true, metrics: null }),
  };
  const engine = new OutputEngine({
    store,
    origin: () => "http://127.0.0.1:3000",
    resolveDisplay: () => ({
      projectId: "project-1",
      projectName: "Demo",
      displayId: "display-1",
      displayName: "Demo Display",
      slug: "demo",
      width: 1920,
      height: 1080,
      enabled: true,
    }),
    windows: {
      open: async () => ({ ok: true }),
      close: () => {},
    },
    discoverDevices: input.discoverDevices ?? (() => []),
    diskRecording,
    resolveProjectName: () => "Demo",
  });
  return { engine, store, diskRecording };
}

