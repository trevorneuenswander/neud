test("8–9: disk activation bypasses monitor checks and uses recording validation", async () => {
  let started = false;
  let validatedFolder = null;
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "neud-record-"));
  const { engine, diskRecording } = createEngine({
    discoverDevices: () => [],
    diskRecording: {
      codecs: () => [{ format: "prores-4444-mov", available: true }],
      platform: () => ({ encoder: "test", available: true }),
      setOnChange: () => {},
      getMetrics: () => null,
      start: async (payload) => {
        started = true;
        validatedFolder = payload.configuration.destinationFolder;
        if (!payload.configuration.destinationFolder) {
          return { ok: false, code: "folder-required", error: "Choose a destination folder." };
        }
        return {
          ok: true,
          metrics: {
            lifecycle: "recording",
            startedAt: new Date().toISOString(),
            durationSeconds: 0,
            outputPath: null,
            tempPath: null,
            byteSize: 0,
            droppedFrames: 0,
            encodedFrames: 1,
            actualFps: null,
            writeBytesPerSecond: null,
            availableDiskBytes: null,
            format: "prores-4444-mov",
            supportsAlpha: true,
            lastError: null,
          },
        };
      },
      stop: async () => ({ ok: true, metrics: null }),
    },
  });

  const route = engine.create({
    projectId: "project-1",
    displayId: "display-1",
    deviceId: DISK_RECORDING_DEVICE_ID,
    recording: { destinationFolder: tmp, width: 1920, height: 1080, frameRateId: "29.97" },
  });
  assert.equal(route.adapterType, "disk");

  const result = await engine.start(route.id);
  assert.equal(result.ok, true);
  assert.equal(started, true);
  assert.equal(validatedFolder, tmp);
  assert.notEqual(result.error, "Selected monitor is disconnected");
  assert.equal(result.route?.session.status, "recording");

  const missingFolder = engine.create({
    projectId: "project-1",
    displayId: "display-1",
    deviceId: DISK_RECORDING_DEVICE_ID,
    recording: { destinationFolder: "" },
  });
  diskRecording.start = async (payload) => {
    if (!payload.configuration.destinationFolder) {
      return { ok: false, code: "folder-required", error: "Choose a destination folder." };
    }
    return { ok: false, code: "unexpected", error: "should not reach" };
  };
  const failed = await engine.start(missingFolder.id);
  assert.equal(failed.ok, false);
  assert.match(failed.error ?? "", /folder/i);
  assert.notEqual(failed.error, "Selected monitor is disconnected");
});

