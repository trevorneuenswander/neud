#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const outputPath = path.join(
  repoRoot,
  "src/lib/developer-tools/display-runtime-embedded.generated.ts",
);

const normalize = fs.readFileSync(
  path.join(repoRoot, "shared/display-runtime/browser/normalize-display-snapshot.js"),
  "utf8",
);
const publisher = fs.readFileSync(
  path.join(repoRoot, "shared/display-runtime/browser/display-runtime-publisher.js"),
  "utf8",
);
const hostedInbound = fs.readFileSync(
  path.join(repoRoot, "shared/display-runtime/browser/hosted-bridge-inbound.js"),
  "utf8",
);
const legacyTickerBridge = fs.readFileSync(
  path.join(repoRoot, "desktop/src/displays/legacy-ticker-live-bridge.js"),
  "utf8",
);
const legacyPylonBridge = fs.readFileSync(
  path.join(repoRoot, "desktop/src/displays/legacy-pylon-live-bridge.js"),
  "utf8",
);

const contents = `// Generated by shared/display-runtime/sync-embedded-scripts.mjs — do not edit.
export const NORMALIZE_DISPLAY_RUNTIME_SCRIPT = ${JSON.stringify(normalize)};
export const DISPLAY_RUNTIME_PUBLISHER_SCRIPT = ${JSON.stringify(publisher)};
export const HOSTED_BRIDGE_INBOUND_SCRIPT = ${JSON.stringify(hostedInbound)};
export const LEGACY_TICKER_LIVE_BRIDGE_SCRIPT = ${JSON.stringify(legacyTickerBridge)};
export const LEGACY_PYLON_LIVE_BRIDGE_SCRIPT = ${JSON.stringify(legacyPylonBridge)};
`;

fs.writeFileSync(outputPath, contents);
console.log("Wrote", outputPath);
